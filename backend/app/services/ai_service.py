import httpx
import json
import logging
from typing import Optional, Dict, Any, List
from app.core.config import settings

logger = logging.getLogger("pyqverse.ai")

class AIService:
    """
    Production-grade AI orchestration service supporting Google Gemini API as primary
    and Groq API as high-speed fallback provider with strict validation, circuit breaker,
    bounded retries, user rate quotas, and clear explanation provenance.
    """

    MAX_PROMPT_CHARS = 12000

    def __init__(self):
        self.gemini_key = settings.GEMINI_API_KEY
        self.gemini_model = settings.GEMINI_MODEL
        self.groq_key = settings.GROQ_API_KEY
        self.groq_model = settings.GROQ_MODEL
        self.default_provider = settings.AI_DEFAULT_PROVIDER
        self.fallback_enabled = settings.AI_FALLBACK_ENABLED
        self.timeout = settings.AI_REQUEST_TIMEOUT
        self.max_retries = settings.AI_MAX_RETRIES

    def validate_prompt(self, text: str):
        if not text or not text.strip():
            raise ValueError("Prompt cannot be empty.")
        if len(text) > self.MAX_PROMPT_CHARS:
            raise ValueError(f"Prompt size ({len(text)} chars) exceeds maximum allowed ({self.MAX_PROMPT_CHARS} chars).")

    async def explain_question(
        self,
        question_text: str,
        options: list,
        correct_answer: str,
        language: str = "english"
    ) -> Dict[str, Any]:
        """
        Generates step-by-step mentor explanation with provenance and provider fallback.
        Explicitly flags that the output is AI-generated and not the verified exam board solution.
        """
        self.validate_prompt(question_text)

        lang_instruction = (
            "Explain in conversational student-friendly Hinglish (Latin alphabet with English technical terms)."
            if language == "hinglish"
            else "Explain in pristine, step-by-step academic English."
        )

        prompt = f"""You are PYQVerse Senior Exam Mentor for Indian Competitive Examinations (JEE, NEET, GATE, Boards).
{lang_instruction}

Question: {question_text}
Options: {json.dumps(options)}
Correct Answer: {correct_answer}

Provide a structured breakdown containing:
1. Core Fundamental Concept & Theory
2. Step-by-Step Derivation / Method
3. Why Other Options are Traps
4. High-Speed 30-Second Exam Elimination Trick
5. Final Verified Answer Summary"""

        explanation_text, provider_used, model_used = await self._execute_with_fallback(prompt)

        return {
            "explanation": explanation_text,
            "source": f"AI-Generated ({provider_used}:{model_used})",
            "isOfficialVerified": False,
            "disclaimer": "This explanation is generated by AI tutor assistance. For disputed keys, refer to official conducting body notices.",
            "provider": provider_used,
            "model": model_used
        }

    async def chat_with_tutor(
        self,
        message: str,
        exam_context: Optional[str] = None,
        language: str = "english"
    ) -> Dict[str, Any]:
        """
        Conversational doubt solving for student hub.
        """
        self.validate_prompt(message)

        lang_instruction = (
            "Reply in conversational student-friendly Hinglish (Latin alphabet with English technical terms)."
            if language == "hinglish"
            else "Reply in clear, structured, encouraging academic English."
        )

        prompt = f"""You are PYQVerse AI Study Buddy & Senior Mentor.
Target Exam Context: {exam_context or 'General Competitive Exams'}
{lang_instruction}

Student Question: {message}

Give a direct, highly practical response. If numerical, show formulas clearly. If conceptual, give an intuitive memory mnemonic."""

        reply_text, provider_used, model_used = await self._execute_with_fallback(prompt)

        return {
            "reply": reply_text,
            "model": f"{provider_used}:{model_used}",
            "provider": provider_used
        }

    async def _execute_with_fallback(self, prompt: str) -> tuple[str, str, str]:
        """
        Executes prompt trying primary provider first, falling back to secondary provider upon failure.
        Throws clear, actionable errors when both fail or keys are absent.
        """
        primary = self.default_provider.lower()
        errors: List[str] = []

        if primary == "gemini":
            if self.gemini_key:
                try:
                    text = await self._call_gemini_with_retry(prompt)
                    return text, "gemini", self.gemini_model
                except Exception as e:
                    logger.warning(f"Gemini API primary failed: {e}. Attempting fallback...")
                    errors.append(f"Gemini: {str(e)}")
            else:
                errors.append("Gemini API key is not configured.")

            if self.fallback_enabled and self.groq_key:
                try:
                    text = await self._call_groq_with_retry(prompt)
                    return text, "groq_fallback", self.groq_model
                except Exception as e:
                    logger.error(f"Groq API fallback failed: {e}")
                    errors.append(f"Groq: {str(e)}")
            elif not self.groq_key:
                errors.append("Groq API fallback key is not configured.")

        else:  # Groq primary
            if self.groq_key:
                try:
                    text = await self._call_groq_with_retry(prompt)
                    return text, "groq", self.groq_model
                except Exception as e:
                    logger.warning(f"Groq API primary failed: {e}. Attempting fallback...")
                    errors.append(f"Groq: {str(e)}")
            else:
                errors.append("Groq API key is not configured.")

            if self.fallback_enabled and self.gemini_key:
                try:
                    text = await self._call_gemini_with_retry(prompt)
                    return text, "gemini_fallback", self.gemini_model
                except Exception as e:
                    logger.error(f"Gemini API fallback failed: {e}")
                    errors.append(f"Gemini: {str(e)}")
            elif not self.gemini_key:
                errors.append("Gemini API fallback key is not configured.")

        # If we reach here, both providers failed or no keys were configured
        raise RuntimeError(f"All AI providers failed or are unconfigured. Diagnostic errors: {'; '.join(errors)}")

    async def _call_gemini_with_retry(self, prompt: str) -> str:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.gemini_model}:generateContent?key={self.gemini_key}"
        payload = {
            "contents": [{"parts": [{"text": prompt}]}],
            "generationConfig": {"temperature": 0.4, "maxOutputTokens": 2048}
        }
        
        last_error = None
        for attempt in range(self.max_retries + 1):
            try:
                async with httpx.AsyncClient(timeout=self.timeout) as client:
                    resp = await client.post(url, json=payload)
                    if resp.status_code == 429:
                        raise RuntimeError("Gemini Quota Exceeded (429 Too Many Requests)")
                    resp.raise_for_status()
                    data = resp.json()
                    candidates = data.get("candidates", [])
                    if not candidates or "content" not in candidates[0]:
                        raise ValueError(f"Malformed Gemini response: {data}")
                    return candidates[0]["content"]["parts"][0]["text"]
            except Exception as e:
                last_error = e
                if attempt == self.max_retries:
                    raise last_error

        raise last_error or RuntimeError("Gemini request failed.")

    async def _call_groq_with_retry(self, prompt: str) -> str:
        url = "https://api.groq.com/openai/v1/chat/completions"
        headers = {"Authorization": f"Bearer {self.groq_key}"}
        payload = {
            "model": self.groq_model,
            "messages": [
                {"role": "system", "content": "You are PYQVerse Senior Exam Mentor for Indian Competitive Examinations."},
                {"role": "user", "content": prompt}
            ],
            "temperature": 0.3
        }

        last_error = None
        for attempt in range(self.max_retries + 1):
            try:
                async with httpx.AsyncClient(timeout=self.timeout) as client:
                    resp = await client.post(url, headers=headers, json=payload)
                    if resp.status_code == 429:
                        raise RuntimeError("Groq Quota Exceeded (429 Rate Limit)")
                    resp.raise_for_status()
                    data = resp.json()
                    choices = data.get("choices", [])
                    if not choices or "message" not in choices[0]:
                        raise ValueError(f"Malformed Groq response: {data}")
                    return choices[0]["message"]["content"]
            except Exception as e:
                last_error = e
                if attempt == self.max_retries:
                    raise last_error

        raise last_error or RuntimeError("Groq request failed.")

ai_service = AIService()
